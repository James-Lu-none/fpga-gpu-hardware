    // otherwise awid, bid, arid, rid wont be generated
    axi_dwidth_converter_0 u_dwidth_conv (
        .s_axi_aclk (axi_aclk),
        .s_axi_aresetn (axi_aresetn),

        // 64-bit Slave Interface from XDMA
        .s_axi_awid (xdma_dwconv_axi.awid),
