        // .s_axi_arregion ({dwconv_xbar_axi.arregion, gpu_xbar_axi.arregion}), // region is omitted in crossbar
        .s_axi_arvalid ({dwconv_xbar_axi.arvalid, gpu_xbar_axi.arvalid}),
