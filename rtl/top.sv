    // 1. PCIe Reference Clock Buffer (IBUFDS_GTE2 Primitive)
    wire pcie_ref_clk;
    IBUFDS_GTE2 u_ibufds_gte2 (
        .I (sys_clk_clk_p),
        .IB (sys_clk_clk_n),
        .CEB (1'b0),
        .O (pcie_ref_clk),
        .ODIV2 ()
    );

    // Hardware Reset Logic (Combine external PCIe reset with physical button)
