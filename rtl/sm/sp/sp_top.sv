`timescale 1ns / 1ps
// Streaming Multiprocessor (SM) Compute Core - TRUE SIMT ARCHITECTURE
// Top-level module encapsulating the Warp Scheduler, Fetch/Decode, 
// Vector Register File, and Execution Pipeline.

`include "gpu_defines.vh"

module sub_partition (
    input wire clk,
    input wire rst_n,

    // Instruction Load Interface (From Hardware Engine)
    input wire iram_we,
    input wire [11:0] iram_waddr,
    input wire [31:0] iram_wdata,

    // Warp Launch Interface (From Warp Scheduler)
    warp_alloc_if.slave alloc,
    input wire [15:0] block_dim_x,

    // Memory Interface (To SM-Level Dynamic Coalescing Engine)
    output wire                          mem_req_valid,
    output wire                          mem_req_is_load,
    output wire [$clog2(`MAX_WARPS)-1:0] mem_req_warp_id,
    output wire [4:0]                    mem_req_rd,
    output wire [11:0]                   mem_req_pc,
    output wire [`NUM_LANES-1:0]         mem_req_mask,
    output wire [`WARP_DATA_W-1:0]       mem_req_addr,
    output wire [`WARP_DATA_W-1:0]       mem_req_wdata,
    input  wire                          mem_req_ready,

    input  wire                          mem_rsp_valid,
    input  wire [$clog2(`MAX_WARPS)-1:0] mem_rsp_warp_id,
    input  wire [4:0]                    mem_rsp_rd,
    input  wire [11:0]                   mem_rsp_pc,
    input  wire [`NUM_LANES-1:0]         mem_rsp_mask,
    input  wire                          mem_rsp_is_load,
    input  wire [`WARP_DATA_W-1:0]       mem_rsp_rdata
`ifdef ENABLE_GPU_DEBUG
    , input wire perf_clear,
    output wire [`PERF_COUNT-1:0] perf_events
`endif
);

    // Reset Pipeline (Level 3)
    // Reset distribution stage, not a CDC synchronizer. Allow driver replication.
    reg core_rst_n_reg;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) core_rst_n_reg <= 1'b0;
        else        core_rst_n_reg <= 1'b1;
    end
    wire core_rst_n = core_rst_n_reg;

`ifdef ENABLE_GPU_DEBUG
    wire [`PERF_COUNT-1:0] ctrl_events, dpath_events;
    assign perf_events = ctrl_events | dpath_events;
`endif
    // Inter-module Interconnect Interfaces
    issue_if issue();
    operand_if op();
    
    // alu_wb: Generated by ALU execution pipeline for register-writing instructions (ADD, SUB, MUL, ADDI, S2R)
    // lsu_wb: Generated by Load/Store Unit only for memory read instructions (LDR, load memory data to register)
    // lsu_wb.valid is only asserted when there's a LDR instruction
    // * VRF has only one write port, but two sources wants to write to it, which creates a structural hazard, 
    // since memory reads have high and variable latency, so LSU is prioritized over ALU to avoid memory response drops, 
    // secondly, prioritizing LSU can unstall the waiting warp as early as possible.
    wb_if alu_wb();
    ctx_wb_if ctx_alu_wb();
    
    // wb signals from lsu
    wb_if lsu_wb();
    ctx_wb_if ctx_lsu_wb(); // LSU doesn't really generate branch convergence, but we use interface anyway
    
    // wb commits data to physical registers (not all instructions write registers).
    // ctx_wb commits control flow and lifecycle to the warp scheduler.
    wb_if wb();
    ctx_wb_if ctx_wb();
    
    wire [2:0] alu_fn;
    wire ex1_valid, ex1_writes_reg;
    wire [$clog2(`MAX_WARPS)-1:0] ex1_warp_id;
    wire [4:0] ex1_rd;

    sp_ctrl u_sp_ctrl (
        .clk(clk),
        .rst_n(core_rst_n),
        .alloc(alloc),
        .issue(issue),
        .op(op),
        .alu_wb(alu_wb),
        .lsu_wb(lsu_wb),
        .ctx_lsu_wb(ctx_lsu_wb),
        .ctx_alu_wb(ctx_alu_wb),
        .ctx_wb(ctx_wb),
        .wb(wb),
        .alu_fn(alu_fn),
        .ex1_valid(ex1_valid),
        .ex1_writes_reg(ex1_writes_reg),
        .ex1_warp_id(ex1_warp_id),
        .ex1_rd(ex1_rd)
`ifdef ENABLE_GPU_DEBUG
        , .perf_clear(perf_clear), .perf_events(ctrl_events)
`endif
    );
    sp_dpath u_sp_dpath (
        .clk(clk),
        .rst_n(core_rst_n),
        .block_dim_x(block_dim_x),
        .iram_we(iram_we),
        .iram_waddr(iram_waddr),
        .iram_wdata(iram_wdata),
        .issue(issue),
        .op(op),
        .wb(wb),
        .alu_wb(alu_wb),
        .lsu_wb(lsu_wb),
        .ctx_lsu_wb(ctx_lsu_wb),
        .alu_fn(alu_fn),
        .ex1_valid(ex1_valid),
        .ex1_writes_reg(ex1_writes_reg),
        .ex1_warp_id(ex1_warp_id),
        .ex1_rd(ex1_rd),
        .mem_req_valid(mem_req_valid),
        .mem_req_is_load(mem_req_is_load),
        .mem_req_warp_id(mem_req_warp_id),
        .mem_req_rd(mem_req_rd),
        .mem_req_pc(mem_req_pc),
        .mem_req_mask(mem_req_mask),
        .mem_req_addr(mem_req_addr),
        .mem_req_wdata(mem_req_wdata),
        .mem_req_ready(mem_req_ready),
        .mem_rsp_valid(mem_rsp_valid),
        .mem_rsp_warp_id(mem_rsp_warp_id),
        .mem_rsp_rd(mem_rsp_rd),
        .mem_rsp_pc(mem_rsp_pc),
        .mem_rsp_mask(mem_rsp_mask),
        .mem_rsp_is_load(mem_rsp_is_load),
        .mem_rsp_rdata(mem_rsp_rdata)
`ifdef ENABLE_GPU_DEBUG
        , .perf_events(dpath_events)
`endif
    );
endmodule
